def write_csv(rows: list[dict[str, Any]], path: Path) -> None:
    with open(path, "w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(FIELDS))
        writer.writeheader()
        writer.writerows(rows)


def write_fixture_dataset(
    directory: "str | Path",
    *,
    seed: int = 7,
    n_securities: int = 60,
    ret_signal: float = 0.02,
    ret_noise: float = 0.06,
    dataset_id: str = FIXTURE_DATASET_ID,
    manifest_name: str = "manifest.json",
) -> Path:
    """Write ``panel.csv`` and an operator-style manifest into ``directory``; returns the manifest path."""
    root = Path(directory)
    root.mkdir(parents=True, exist_ok=True)
    write_csv(
        generate_rows(
            seed=seed,
            n_securities=n_securities,
            ret_signal=ret_signal,
            ret_noise=ret_noise,
        ),
        root / "panel.csv",
    )
    manifest_path = root / manifest_name
    manifest_path.write_text(
        json.dumps(
            fixture_manifest(dataset_id=dataset_id), indent=2, sort_keys=True
        ),
        encoding="utf-8",
    )
    return manifest_path
